import 'package:audioplayers/audioplayers.dart';

/// The two short sounds a check can end with.
///
/// Like haptics, there is no sound for a failed check.
///
/// An interface, so tests can swap in a fake that records which sound was
/// asked for, and so the real player can be replaced without touching the
/// code that decides when to play.
abstract interface class SoundService {
  /// Loads the sounds ahead of time, so the first one plays the moment a
  /// result appears instead of after a pause. Safe to call more than once.
  Future<void> warmUp();

  /// Breaches were found: a subdued two-note notification.
  Future<void> breached();

  /// No known breaches were found: a soft confirmation.
  Future<void> clean();

  /// Releases the players. Safe to call once, when done.
  Future<void> dispose();
}

/// Plays the two sounds bundled in `assets/sounds/`.
///
/// The files are generated by `tool/generate_sounds.py` and are original to
/// this project. Nothing is ever fetched from the network.
///
/// The players are set up to behave like quiet interface sounds, not like
/// media:
///
///  * **iOS**: the "ambient" audio session. It is silenced by the Ring/Silent
///    switch and mixes with whatever is already playing rather than
///    interrupting it.
///  * **Android**: played as a notification-type sonification, on the stream
///    that silent mode, vibrate mode and Do Not Disturb mute, and without
///    taking audio focus, so music keeps playing.
///  * **Desktop and web**: there is no silent mode to follow. The sound plays
///    at the system (or browser tab) volume and is silent when that is muted.
///
/// Nothing here runs until a sound is first needed, so while result sounds
/// are switched off (the default) the app never touches the audio system.
///
/// Every failure is swallowed. A device that can't play sound should stay
/// quiet, never hold up or disturb a result.
class AssetSoundService implements SoundService {
  /// Paths are relative to `assets/`, which is where the player looks.
  static const String breachAsset = 'sounds/result_breach.wav';
  static const String clearAsset = 'sounds/result_clear.wav';

  /// Below full volume: the files are already quiet, and this keeps them so.
  static const double _volume = 0.7;

  AudioPlayer? _breach;
  AudioPlayer? _clear;
  Future<void>? _loading;
  bool _disposed = false;

  @override
  Future<void> warmUp() => _loading ??= _load();

  Future<void> _load() async {
    try {
      await AudioPlayer.global.setAudioContext(
        AudioContext(
          android: const AudioContextAndroid(
            contentType: AndroidContentType.sonification,
            usageType: AndroidUsageType.notification,
            audioFocus: AndroidAudioFocus.none,
          ),
          iOS: AudioContextIOS(category: AVAudioSessionCategory.ambient),
        ),
      );
      _breach = await _prepare(breachAsset);
      _clear = await _prepare(clearAsset);
    } catch (_) {
      // No audio on this device, or the plugin isn't available: stay silent.
      _breach = null;
      _clear = null;
    }
  }

  Future<AudioPlayer> _prepare(String asset) async {
    final player = AudioPlayer();
    // lowLatency suits a half-second clip; `stop` keeps it loaded for replay.
    await player.setPlayerMode(PlayerMode.lowLatency);
    await player.setReleaseMode(ReleaseMode.stop);
    await player.setVolume(_volume);
    await player.setSource(AssetSource(asset));
    return player;
  }

  @override
  Future<void> breached() => _play(() => _breach);

  @override
  Future<void> clean() => _play(() => _clear);

  Future<void> _play(AudioPlayer? Function() pick) async {
    if (_disposed) return;
    try {
      await warmUp();
      final player = pick();
      if (player == null || _disposed) return;
      // Rewind, in case the same sound is still finishing, then play.
      await player.stop();
      await player.resume();
    } catch (_) {}
  }

  @override
  Future<void> dispose() async {
    _disposed = true;
    try {
      await _breach?.dispose();
      await _clear?.dispose();
    } catch (_) {}
    _breach = null;
    _clear = null;
  }
}

/// Plays nothing. The default in tests.
class NoSoundService implements SoundService {
  const NoSoundService();

  @override
  Future<void> warmUp() async {}

  @override
  Future<void> breached() async {}

  @override
  Future<void> clean() async {}

  @override
  Future<void> dispose() async {}
}
